# The Wibawa demo: a small batik shop admin in one file.
#
#   bundle exec rake demo          # http://localhost:3000/admin
#   bundle exec rake demo:reset    # throw the data away and seed again
#
# It runs in development, where Wibawa needs no sign-in. Do not deploy it.
ENV["RAILS_ENV"] ||= "development"
ENV["DATABASE_URL"] ||= "sqlite3:#{File.expand_path('tmp/demo.sqlite3', __dir__)}"

require "fileutils"
require "rails"
require "active_record/railtie"
require "action_controller/railtie"
require "action_view/railtie"
require "propshaft"
require "mcp"
require "wibawa"

FileUtils.mkdir_p(File.expand_path("tmp", __dir__))

module Demo
  class Application < Rails::Application
    config.root = __dir__
    config.load_defaults Rails::VERSION::STRING.to_f
    config.eager_load = false
    config.secret_key_base = "demo-only-not-a-secret"
    config.hosts.clear
    config.consider_all_requests_local = true
    config.logger = Logger.new($stdout, level: :info)
  end
end

Wibawa.config.load_paths = [File.expand_path("wibawa", __dir__)]

DemoUser = Struct.new(:id, :name)
DEMO_USER = DemoUser.new(1, "Demo admin")

Wibawa.configure do |config|
  config.site_title = "Toko Kawung"
  config.current_user = -> { DEMO_USER }
  config.currency = "IDR"
  config.saved_views = true
  config.audit_log = true
  # An agent can connect with: Authorization: Bearer demo-token
  config.mcp_authenticate_with { |token| DEMO_USER if token == "demo-token" }
end

class ApplicationRecord < ActiveRecord::Base
  self.abstract_class = true
end

class Customer < ApplicationRecord
  has_many :orders, dependent: :restrict_with_error
  validates :name, presence: true
end

class Product < ApplicationRecord
  has_many :line_items, dependent: :restrict_with_error
  validates :name, :sku, presence: true
  validates :price, numericality: { greater_than: 0 }
  scope :active, -> { where(active: true) }
  scope :low_stock, -> { where(stock: ...10) }
end

class Order < ApplicationRecord
  belongs_to :customer
  has_many :line_items, -> { order(:position) }, dependent: :destroy
  accepts_nested_attributes_for :line_items, allow_destroy: true
  enum :status, { pending: 0, paid: 1, shipped: 2, cancelled: 3 }
  validates :number, presence: true, uniqueness: true
  before_save :add_up

  private

  def add_up
    items = line_items.reject(&:marked_for_destruction?)
    self.total = items.sum { |item| item.quantity.to_i * item.unit_price.to_d } if items.any?
  end
end

class LineItem < ApplicationRecord
  belongs_to :order
  belongs_to :product
  validates :quantity, numericality: { greater_than: 0 }
  before_validation { self.unit_price ||= product&.price }
end

Demo::Application.initialize!

unless ActiveRecord::Base.connection.table_exists?(:orders)
  ActiveRecord::Schema.verbose = false
  ActiveRecord::Schema.define do
    create_table :customers do |t|
      t.string :name, null: false
      t.string :email
      t.string :city
      t.timestamps
    end
    create_table :products do |t|
      t.string :name, null: false
      t.string :sku, null: false
      t.decimal :price, null: false
      t.integer :stock, null: false, default: 0
      t.boolean :active, null: false, default: true
      t.timestamps
    end
    create_table :orders do |t|
      t.string :number, null: false
      t.integer :status, null: false, default: 0
      t.decimal :total, null: false, default: 0
      t.references :customer, null: false
      t.text :notes
      t.timestamps
    end
    create_table :line_items do |t|
      t.references :order, null: false
      t.references :product, null: false
      t.integer :quantity, null: false, default: 1
      t.decimal :unit_price
      t.integer :position
    end
    create_table :wibawa_saved_views do |t| # as generated by wibawa:saved_views
      t.string :resource_key, null: false
      t.string :name, null: false
      t.text :query, null: false, default: ""
      t.string :owner
      t.timestamps
    end
    create_table :wibawa_audit_entries do |t| # as generated by wibawa:audit_log
      t.string :actor
      t.string :actor_label
      t.string :action, null: false
      t.string :via, null: false
      t.string :resource_key, null: false
      t.string :record_id
      t.string :record_label
      t.json :data
      t.datetime :created_at, null: false
    end
  end
  load File.expand_path("seeds.rb", __dir__)
end

Demo::Application.routes.draw do
  mount Wibawa::Engine, at: "/admin"
  root to: redirect("/admin")
  get "/favicon.ico", to: ->(_env) { [204, {}, []] }
end
