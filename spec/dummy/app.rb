# A one-file Rails app that mounts the engine, so specs exercise the real
# controllers, components and views.
ENV["RAILS_ENV"] = "test"
ENV["DATABASE_URL"] = "sqlite3::memory:"

require "rails"
require "active_record/railtie"
require "action_controller/railtie"
require "action_view/railtie"
require "active_storage/engine"
require "action_text/engine"
require "rails-i18n"
require "propshaft" # serves the gem's CSS and JavaScript to the system specs
require "wibawa"

module Dummy
  class Application < Rails::Application
    config.root = __dir__
    config.load_defaults Rails::VERSION::STRING.to_f
    config.eager_load = false
    config.secret_key_base = "test"
    config.hosts.clear
    config.logger = Logger.new(nil)
    config.action_dispatch.show_exceptions = :none
    config.action_controller.allow_forgery_protection = false # as in a generated test.rb
    # Active Storage and Action Text extend models while the app boots, so this one loads then.
    initializer("dummy.product") { require_relative "product" }
    config.active_storage.service = :test
    config.active_storage.service_configurations = { test: { service: "Disk", root: File.join(__dir__, "tmp/storage") } }
  end
end

Wibawa.config.load_paths = [ File.join(__dir__, "wibawa") ]

class ApplicationRecord < ActiveRecord::Base
  self.abstract_class = true
end

class Customer < ApplicationRecord
  has_many :orders
end

class Order < ApplicationRecord
  belongs_to :customer
  has_many :line_items, dependent: :destroy
  accepts_nested_attributes_for :line_items, allow_destroy: true
  enum :status, { pending: 0, paid: 1 }
  validates :number, presence: true
end

class LineItem < ApplicationRecord
  belongs_to :order
end

# Models are defined above so resource files can name them at boot;
# the schema comes after, once the in-memory database is connected.
Dummy::Application.initialize!

ActiveRecord::Schema.verbose = false
ActiveRecord::Schema.define do
  create_table(:customers) { |t| t.string :name }
  create_table :orders do |t|
    t.string :number
    t.integer :status, default: 0
    t.decimal :total
    t.references :customer
    t.timestamps
  end
  create_table :wibawa_saved_views do |t| # as generated by wibawa:saved_views
    t.string :resource_key, null: false
    t.string :name, null: false
    t.text :query, null: false, default: ""
    t.string :owner
    t.timestamps
  end
  create_table :wibawa_audit_entries do |t| # as generated by wibawa:audit_log
    t.string :actor
    t.string :actor_label
    t.string :action, null: false
    t.string :via, null: false
    t.string :resource_key, null: false
    t.string :record_id
    t.string :record_label
    t.json :data
    t.datetime :created_at, null: false
  end
  create_table(:products) { |t| t.string :name }
  # Active Storage and Action Text tables, as their install generators create them.
  create_table :active_storage_blobs do |t|
    t.string :key, null: false
    t.string :filename, null: false
    t.string :content_type
    t.text :metadata
    t.string :service_name, null: false
    t.bigint :byte_size, null: false
    t.string :checksum
    t.datetime :created_at, null: false
  end
  create_table :active_storage_attachments do |t|
    t.string :name, null: false
    t.references :record, null: false, polymorphic: true, index: false
    t.references :blob, null: false
    t.datetime :created_at, null: false
  end
  create_table :active_storage_variant_records do |t|
    t.belongs_to :blob, null: false, index: false
    t.string :variation_digest, null: false
  end
  create_table :action_text_rich_texts do |t|
    t.string :name, null: false
    t.text :body
    t.references :record, null: false, polymorphic: true, index: false
    t.timestamps
  end
  create_table :line_items do |t|
    t.references :order
    t.string :product
    t.integer :position
  end
end
